import type { ActionsFile, MorphModel, ReportSpec } from '@morph-reports/spec';
import { compileViewSql, qi, resolveReport } from '@morph-reports/spec';
import { AUDIT_SQL, FUNCTIONS_SQL } from './functions.js';

export interface MigrationOptions {
  /** Roles (values of a profile `role` column) allowed to read everyone's audit rows. Default: none (actor only). */
  auditReaders?: { schema: string; table: string; pk: string; roleColumn: string; roles: string[] };
  /** Morph package version, written in the header. */
  version?: string;
}

/** Allow-list entry baked into `morph__action_def()`. */
export interface ActionDef {
  id: string;
  kind: 'set_enum' | 'set_fk';
  enabled: boolean;
  schema: string;
  table: string;
  column: string;
  col_type: string;
  pk: string;
  pk_type: string;
  display: string | null;
  values?: string[];
  labels?: Record<string, string>;
  terminal?: string[];
  target?: { schema: string; table: string; pk: string; display: string | null };
  side_effects: string[];
  bulk_max: number;
}

/** Quotes a Postgres type for use after `::`. `public.deal_stage` -> `"public"."deal_stage"`. */
export function quoteType(pgType: string): string {
  const base = pgType.replace(/\(.*\)$/, '').trim();
  if (/^[a-z][a-z0-9 ]*$/i.test(base) && !base.includes('.')) return base; // built-in: text, uuid, bigint, numeric...
  return base
    .split('.')
    .map((p) => qi(p.replace(/^"|"$/g, '')))
    .join('.');
}

export function buildActionDefs(model: MorphModel, actions: ActionsFile): Record<string, ActionDef> {
  const out: Record<string, ActionDef> = {};
  for (const a of actions.actions) {
    const ent = model.entities[a.table];
    if (!ent || !ent.primaryKey) continue;
    const col = ent.fields[a.column];
    const pk = ent.fields[ent.primaryKey];
    if (!col || !pk) continue;
    const def: ActionDef = {
      id: a.id,
      kind: a.kind,
      enabled: a.enabled,
      schema: ent.schema,
      table: a.table,
      column: a.column,
      col_type: quoteType(col.pgType),
      pk: ent.primaryKey,
      pk_type: quoteType(pk.pgType),
      display: ent.displayField,
      side_effects: (a.sideEffects ?? []).map((s) => s.set).filter((c) => ent.fields[c]),
      bulk_max: a.bulkMax,
    };
    if (a.kind === 'set_enum') {
      def.values = a.values ?? [];
      def.terminal = a.terminal ?? [];
      const en = col.enum ? model.enums[col.enum] : undefined;
      if (en) def.labels = en.labels;
    } else if (a.target) {
      const t = model.entities[a.target.entity];
      if (t) def.target = { schema: t.schema, table: t.name, pk: a.target.field, display: a.target.display };
    }
    out[a.id] = def;
  }
  return out;
}

/** The profile table that maps auth.uid() to a display name (users, profiles...). */
export function findActorTable(model: MorphModel): { schema: string; table: string; pk: string; display: string } | null {
  for (const e of Object.values(model.entities)) {
    if (!e.primaryKey || !e.displayField || e.rls === 'rls_off') continue;
    const pk = e.fields[e.primaryKey];
    if (pk?.references?.entity === 'auth.users' || (pk?.references?.entity === 'users' && pk.references.inferred === false && e.name !== 'users')) {
      return { schema: e.schema, table: e.name, pk: e.primaryKey, display: e.displayField };
    }
  }
  return null;
}

function dollarQuote(body: string, base: string): string {
  let tag = base;
  while (body.includes(`$${tag}$`)) tag += '_';
  return `$${tag}$${body}$${tag}$`;
}

/**
 * Writes `supabase/migrations/<ts>_morph.sql` (MO-113): report views, the
 * action allow-list, preview/apply/undo functions and the audit table.
 * Idempotent: `create or replace` and `if not exists` throughout.
 */
export function generateMigration(input: { model: MorphModel; reports: ReportSpec[]; actions: ActionsFile }, opts: MigrationOptions = {}): string {
  const { model, reports, actions } = input;
  const defs = buildActionDefs(model, actions);
  const actor = findActorTable(model);
  const allow = { undo_days: actions.undoDays, actor, actions: defs };
  const allowJson = JSON.stringify(allow, null, 2);

  const readers = opts.auditReaders;
  const canRead = readers
    ? `select p_actor = auth.uid() or exists (select 1 from ${qi(readers.schema)}.${qi(readers.table)} where ${qi(readers.pk)} = auth.uid() and ${qi(readers.roleColumn)} = any (array[${readers.roles.map((r) => `'${r.replace(/'/g, "''")}'`).join(', ')}]))`
    : 'select p_actor = auth.uid()';

  const views = reports
    .filter((r) => !r.broken)
    .map((r) => compileViewSql(resolveReport(r, model, actions)));

  return [
    `-- Morph migration${opts.version ? ` (morph ${opts.version})` : ''}. Generated by \`morph init\`; review it, then run \`supabase db push\`.`,
    '-- Everything here runs as the signed-in viewer: views are security_invoker and functions are SECURITY INVOKER.',
    '-- To remove Morph: drop the morph_r_* views, the morph_* functions and the morph_audit table.',
    '',
    '-- 1. Action allow-list. Table and column names for writes come only from here.',
    `create or replace function public.morph__action_def() returns jsonb language sql immutable security invoker set search_path = '' as ${dollarQuote(`\n  select ${dollarQuote(allowJson, 'json')}::jsonb\n`, 'fn')};`,
    'revoke all on function public.morph__action_def() from public, anon;',
    'grant execute on function public.morph__action_def() to authenticated;',
    '',
    '-- 2. Who can read the audit log (default: only the person who acted).',
    `create or replace function public.morph__can_read_audit(p_actor uuid) returns boolean language sql stable security invoker set search_path = '' as $fn$ ${canRead} $fn$;`,
    'revoke all on function public.morph__can_read_audit(uuid) from public, anon;',
    'grant execute on function public.morph__can_read_audit(uuid) to authenticated;',
    '',
    '-- 3. Audit table (MO-708).',
    AUDIT_SQL.trim(),
    '',
    '-- 4. Preview, apply, undo (MO-705 – MO-707).',
    FUNCTIONS_SQL.trim(),
    '',
    '-- 5. Report views (MO-402). One security_invoker view per kept report.',
    ...views.flatMap((v) => [v, '']),
  ].join('\n');
}

/** `20261102091500_morph.sql` */
export function migrationFileName(now = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0');
  const ts = `${now.getUTCFullYear()}${p(now.getUTCMonth() + 1)}${p(now.getUTCDate())}${p(now.getUTCHours())}${p(now.getUTCMinutes())}${p(now.getUTCSeconds())}`;
  return `${ts}_morph.sql`;
}
